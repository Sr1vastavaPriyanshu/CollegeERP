CREATE TABLE accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  login_id TEXT NOT NULL,
  email TEXT NOT NULL,
  display_name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  account_type TEXT NOT NULL CHECK (account_type IN ('student', 'employee')),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  course_completed BOOLEAN NOT NULL DEFAULT FALSE,
  failed_attempts INTEGER NOT NULL DEFAULT 0 CHECK (failed_attempts >= 0),
  locked_until TIMESTAMPTZ,
  session_version INTEGER NOT NULL DEFAULT 0 CHECK (session_version >= 0),
  reset_token_hash CHAR(64),
  reset_expires_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT reset_token_pair CHECK (
    (reset_token_hash IS NULL AND reset_expires_at IS NULL)
    OR (reset_token_hash IS NOT NULL AND reset_expires_at IS NOT NULL)
  )
);

CREATE UNIQUE INDEX accounts_login_id_ci_unique ON accounts (lower(login_id));
CREATE UNIQUE INDEX accounts_email_ci_unique ON accounts (lower(email));
CREATE INDEX accounts_reset_token_hash_idx ON accounts (reset_token_hash)
  WHERE reset_token_hash IS NOT NULL;

CREATE TABLE audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id BIGINT REFERENCES accounts(id) ON DELETE SET NULL,
  event TEXT NOT NULL,
  ip_address TEXT,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX audit_logs_account_created_idx ON audit_logs (account_id, created_at DESC);
CREATE INDEX audit_logs_created_idx ON audit_logs (created_at DESC);
